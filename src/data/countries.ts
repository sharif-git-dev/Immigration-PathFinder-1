/**
 * Official entry requirements to Canada by country of citizenship:
 * Source: Immigration, Refugees and Citizenship Canada (IRCC)
 * https://www.canada.ca/en/immigration-refugees-citizenship/services/visit-canada/entry-requirements-country.html
 *
 * Entry requirements when travelling to Canada by air:
 *  - 'none': Citizen of Canada or United States (no visa, no eTA required)
 *  - 'eta': Visa-exempt; require Electronic Travel Authorization (eTA) when travelling by air
 *  - 'eta_conditional': Expanded eTA eligible IF flying AND holding valid US non-immigrant visa OR Canadian visa in last 10 yrs; otherwise TRV required.
 *  - 'visa': Temporary Resident Visa (TRV / Visitor Visa) required.
 */

